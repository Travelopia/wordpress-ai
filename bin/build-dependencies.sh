#!/usr/bin/env bash
#
# Build the scoped, self-contained AI dependency bundle committed at
# `dependencies/`.
#
# WordPress 7.0+ ships the PHP AI Client in core under the `WordPress\AiClient\*`
# namespace. This plugin needs the same library, so to avoid a fatal namespace
# collision it bundles its own copy isolated under
# `Travelopia\WordPress_AI\Dependencies\*` via PHP-Scoper.
#
# Pipeline:
#   1. Install the runtime-only dep closure into a throwaway build directory.
#   2. PHP-Scoper rewrites every namespace under the private prefix.
#   3. Regenerate an authoritative classmap autoloader over the scoped sources.
#
# The result (`dependencies/`) is committed, like the JS `dist/`, so consuming
# sites get it without running this build. Re-run after bumping a runtime dep in
# bin/runtime-deps.composer.json.
#
# Usage: composer build:dependencies   (or: bin/build-dependencies.sh)

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

BUILD_DIR="build/runtime"
OUTPUT_DIR="dependencies"
SCOPER="vendor/bin/php-scoper"

if [ ! -x "$SCOPER" ]; then
	echo "error: php-scoper not found — run 'composer install' first." >&2
	exit 1
fi

echo "==> [1/4] Installing runtime dependency closure into ${BUILD_DIR}"
rm -rf "$BUILD_DIR" "$OUTPUT_DIR"
mkdir -p "$BUILD_DIR"
cp bin/runtime-deps.composer.json "$BUILD_DIR/composer.json"
composer install --working-dir="$BUILD_DIR" --no-dev --no-interaction --quiet

echo "==> [2/4] Scoping namespaces under Travelopia\\WordPress_AI\\Dependencies"
"$SCOPER" add-prefix --output-dir="$OUTPUT_DIR" --force --quiet --no-interaction

# PHP-Scoper does not reliably rewrite Composer's pre-generated autoloader maps,
# so discard them and regenerate an authoritative classmap over the scoped
# sources instead.
echo "==> [3/4] Generating scoped autoloader manifest"
rm -rf "$OUTPUT_DIR/composer" "$OUTPUT_DIR/autoload.php"

# Function-include files (composer 'files' autoload) for the pinned dep set,
# derived from build/runtime/vendor/composer/autoload_files.php. Bumping a
# runtime dep may change this list — the verification below fails loudly if so.
FILES=(
	"guzzlehttp/guzzle/src/functions_include.php"
	"ralouphie/getallheaders/src/getallheaders.php"
	"symfony/deprecation-contracts/function.php"
	"symfony/polyfill-php80/bootstrap.php"
	"wordpress/php-ai-client/src/polyfills.php"
)

# Verify the function-include list still matches the installed dep set.
EXPECTED="$(php -r '
	$vendorDir = "'"$ROOT/$BUILD_DIR"'/vendor";
	$baseDir = dirname($vendorDir);
	$files = require "'"$ROOT/$BUILD_DIR"'/vendor/composer/autoload_files.php";
	$rel = array_map(fn($p) => substr($p, strlen($vendorDir) + 1), array_values($files));
	sort($rel);
	echo implode("\n", $rel);
')"
ACTUAL="$(printf '%s\n' "${FILES[@]}" | sort)"
if [ "$EXPECTED" != "$ACTUAL" ]; then
	echo "error: function-include file list is stale. Update FILES in this script to:" >&2
	echo "$EXPECTED" >&2
	exit 1
fi

php -r '
	$files = array_map(fn($f) => "        \"$f\"", $argv[1] ? explode(",", $argv[1]) : []);
	$json = <<<JSON
{
  "name": "travelopia/wordpress-ai-dependencies",
  "description": "Scoped, self-contained AI client runtime bundle. Generated by composer build:dependencies — do not edit by hand.",
  "license": "proprietary",
  "autoload": {
    "classmap": [
      "aysnc/", "guzzlehttp/", "http-interop/", "php-http/",
      "psr/", "ralouphie/", "symfony/", "wordpress/"
    ],
    "files": [
FILES_PLACEHOLDER
    ]
  }
}
JSON;
	echo str_replace("FILES_PLACEHOLDER", implode(",\n", $files), $json) . "\n";
' "$(IFS=,; echo "${FILES[*]}")" > "$OUTPUT_DIR/composer.json"

echo "==> [4/4] Dumping authoritative classmap autoloader"
composer dump-autoload --working-dir="$OUTPUT_DIR" --classmap-authoritative --no-interaction --quiet

# Guard: the scoped bundle must not re-declare the core namespace.
if grep -rqs "^namespace WordPress\\\\AiClient" "$OUTPUT_DIR"; then
	echo "error: scoped bundle still declares an unscoped 'WordPress\\AiClient' namespace." >&2
	exit 1
fi

echo "✓ Scoped dependency bundle built at ${OUTPUT_DIR}/ (entry: ${OUTPUT_DIR}/vendor/autoload.php)"
